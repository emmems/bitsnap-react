// Rewrites src/version.ts from package.json so the SDK can report its version.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const { version } = JSON.parse(readFileSync(new URL("package.json", root), "utf8"));

writeFileSync(
  new URL("src/version.ts", root),
  `// Generated by scripts/write-version.mjs from package.json. Do not edit.\nexport const SDK_VERSION = ${JSON.stringify(version)};\n`,
);
